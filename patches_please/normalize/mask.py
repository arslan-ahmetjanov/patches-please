"""Маскирование найденных секретов (T-021, NFR-004).

Секрет — единственное содержимое находки, которое нельзя показывать: это само
значение, ради которого сработал сканер. Сообщение находки типа `secrets`
заменяется заглушкой целиком, а не вычищается регуляркой по токенам: в
сообщении Gitleaks описание и значение не разделены, а regex по всем текстам
рискует испортить обычные сообщения SAST.

Fingerprint считается до маскирования, по исходному фрагменту
(`patches_please.normalize.sarif`): иначе все находки одного правила в одном
файле получили бы одинаковый хеш и baseline перестал бы их различать
(FR-006, FR-016). Правило, путь и строка при маскировании сохраняются — по ним
разработчик находит место (S-002).

Маскирование действует на новые прогоны: уже сохранённые находки и отчёты
прошлых прогонов не переписываются.
"""

from dataclasses import replace
from typing import Final

from patches_please.normalize.model import Finding, FindingType

MASKED_SECRET: Final = "[секрет скрыт]"


def mask_finding(finding: Finding) -> Finding:
    """Возвращает находку с замаскированным сообщением, если это секрет.

    Меняется только `message` находок типа `secrets`; остальные типы
    возвращаются как есть. Fingerprint копируется без изменений, поэтому
    маскирование не влияет на baseline и дедупликацию.
    """
    if finding.finding_type is not FindingType.SECRETS:
        return finding
    return replace(finding, message=MASKED_SECRET)
